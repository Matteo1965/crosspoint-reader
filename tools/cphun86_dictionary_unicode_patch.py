#!/usr/bin/env python3
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def replace(path: str, old: str, new: str) -> None:
    p = ROOT / path
    text = p.read_text(encoding="utf-8")
    if old not in text:
        raise SystemExit(f"Expected block not found in {path}: {old[:180]!r}")
    p.write_text(text.replace(old, new, 1), encoding="utf-8")


def integrate_generated_font(generated: Path) -> None:
    if not generated.is_file():
        raise SystemExit(f"Generated CPHUN-85 font not found: {generated}")
    text = generated.read_text(encoding="utf-8")
    if "notoserif_14_regular_unicode" not in text:
        raise SystemExit("Unexpected generated font symbols")
    text = text.replace("notoserif_14_regular_unicode", "notoserif_14_regular")
    marker = "/**\n * generated by fontconvert.py"
    replacement = "/**\n * CPHUN-85 dictionary Unicode edition: 1325/1333 dictionary non-ASCII codepoints.\n * Embedded by CPHUN-86 as the built-in Noto Serif 14 pt Regular face.\n * generated by fontconvert.py"
    if marker not in text:
        raise SystemExit("Generated font header marker not found")
    text = text.replace(marker, replacement, 1)
    (ROOT / "lib/EpdFont/builtinFonts/notoserif_14_regular.h").write_text(text, encoding="utf-8")


