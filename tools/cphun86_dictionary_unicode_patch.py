def patch_build_id() -> None:
    replace(
        "src/CPHUNBuildId.h",
        '#define CPHUN_BUILD_ID "CPHUN-260909-84"',
        '#define CPHUN_BUILD_ID "CPHUN-260910-86"',
    )


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: cphun86_dictionary_unicode_patch.py <generated-font-header>")
    integrate_generated_font(Path(sys.argv[1]))
    patch_dictionary_activity()
    patch_renderer_header()
    patch_renderer_cpp()
    patch_build_id()
    print("CPHUN-86 dictionary Unicode integration applied")


if __name__ == "__main__":
    main()
